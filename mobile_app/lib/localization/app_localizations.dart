  /// Reverse lookup map from English string/phrase to localization key
  static Map<String, String>? _reverseLookup;

  static Map<String, String> _getReverseLookup() {
    if (_reverseLookup != null) return _reverseLookup!;
    final map = <String, String>{};
    final en = _localizedValues['en'] ?? {};
    en.forEach((k, v) {
      final clean = v.trim().toLowerCase();
      map[clean] = k;
      // Strip emojis and punctuation for fuzzy resilient matching
      final stripped = clean.replaceAll(RegExp(r'[\u{1F300}-\u{1F9FF}\u{2600}-\u{26FF}\u{2700}-\u{27BF}\u{FE00}-\u{FE0F}]', unicode: true), '').trim();
      if (stripped.isNotEmpty) {
        map[stripped] = k;
      }
    });
    _reverseLookup = map;
    return map;
  }

  /// Translate a given key or raw English string to the current language with fallback
  String translate(String keyOrText, [Map<String, String>? params]) {
    final clean = keyOrText.trim();
    if (clean.isEmpty) return keyOrText;

    final langCode = locale.languageCode.toLowerCase();
    
    // 1. Direct language map lookup by key
    String? text = _localizedValues[langCode]?[clean];
    
    // 2. Try base language without country (e.g. 'zh' for 'zh_tw')
    if (text == null && langCode.contains('_')) {
      final base = langCode.split('_').first;
      text = _localizedValues[base]?[clean];
    }
    
    // 3. Reverse lookup if caller passed raw English text instead of key
    if (text == null) {
      final reverse = _getReverseLookup();
      final lower = clean.toLowerCase();
      String? matchedKey = reverse[lower];
      if (matchedKey == null) {
        final stripped = lower.replaceAll(RegExp(r'[\u{1F300}-\u{1F9FF}\u{2600}-\u{26FF}\u{2700}-\u{27BF}\u{FE00}-\u{FE0F}]', unicode: true), '').trim();
        matchedKey = reverse[stripped];
      }

      if (matchedKey != null) {
        text = _localizedValues[langCode]?[matchedKey];
        if (text == null && langCode.contains('_')) {
          text = _localizedValues[langCode.split('_').first]?[matchedKey];
        }
      }
    }

    // 4. Fallback to English
    text ??= _localizedValues['en']?[clean];

    // 5. Ultimate fallback to input itself
    text ??= keyOrText;

    // Parameter substitution if any provided (e.g. {name})
    if (params != null && params.isNotEmpty) {
      params.forEach((paramKey, paramVal) {
        text = text!.replaceAll('{$paramKey}', paramVal);
      });
    }

    return text!;
  }
